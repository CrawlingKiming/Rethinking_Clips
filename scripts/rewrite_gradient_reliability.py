CONCLUSION = r"""\section{Conclusion}

Fixed-rollout policy optimization is reliable only to the extent that the
rollout continues to support the current learner.  This paper makes that
statement precise at the level of the policy gradient.  The gradient is a
vector-valued importance-sampling estimator, and its conditional mean-squared
error is bounded by a problem-dependent gradient scale divided by sequence
ESS.  Smoothness then converts the resulting high-probability error radius into
a lower bound on one-step population improvement.  The main conclusion is
simple: effective sample size replaces nominal batch size in the reliable
policy-gradient update.

The result explains why a rollout can support many efficient updates before
failing abruptly.  As the current policy moves away from the rollout policy,
order-two R\'enyi divergence increases, sequence ESS decreases, and the
certified gradient radius expands.  The theorem does not identify a universal
ESS threshold, because the transition also depends on gradient scale and signal
strength.  The contextual bandit confirms the predicted relation among ESS,
gradient error, and harmful updates, while the language-model experiments show
that the same sequence-level diagnostic remains informative at scale.  A
natural next step is to estimate the gradient-scale term online and use the
resulting uncertainty radius directly in adaptive update rules."""

PROOFS = r"""\section{Proofs for the theoretical results}
\label{app:proofs}

This appendix proves the gradient-reliability lemma and the population-improvement
theorem.  It then records the intact-group extension and the generic
bias--variance identity used by the frozen-policy diagnostics.

\subsection{Conditional policy-gradient identity}

Condition on $\mathcal F_{k-1}$.  The current parameter is fixed and the unused
responses are drawn from $Q$.  Since $W_k=dP_{\theta_k}/dQ$ and the baseline is
detached and prompt-measurable,
\begin{align}
  \mathbb E_Q[W_kH_k\mid\mathcal F_{k-1}]
  &=
  \mathbb E_{P_{\theta_k}}
  [(R-b(X))\nabla_\theta\log P_{\theta_k}(Y\mid X)
   \mid\mathcal F_{k-1}]\\
  &=
  \nabla J(\theta_k)
  =g_k .
  \label{eq:conditional-gradient-identity}
\end{align}
The baseline term vanishes because the conditional expectation of the score is
zero.

\subsection{Proof of Lemma~\ref{lem:ess-gradient-reliability}}

Let $Z_i:=W_{k,i}H_{k,i}$.  Conditional independence and
Equation~\eqref{eq:conditional-gradient-identity} give
\begin{align}
  \mathbb E[
    \|\widehat g_k-g_k\|_2^2
    \mid\mathcal F_{k-1}]
  &=
  \frac1N
  \mathbb E_Q[
    \|Z_1-g_k\|_2^2
    \mid\mathcal F_{k-1}]\\
  &=
  \frac1N
  \left\{
    \mathbb E_Q[
      W_k^2\|H_k\|_2^2
      \mid\mathcal F_{k-1}]
    -
    \|g_k\|_2^2
  \right\}\\
  &\le
  \frac{\sigma_{g,k}^2}
       {\mathrm{ESS}_k}.
  \label{eq:ess-gradient-mse}
\end{align}
The last line uses Assumption~\ref{ass:weighted-gradient-moment} and
$\mathrm{ESS}_k=N/\mathbb E_Q[W_k^2\mid\mathcal F_{k-1}]$.
Applying Markov's inequality to
$\|\widehat g_k-g_k\|_2^2$ yields
\[
  \Pr\left(
    \|\widehat g_k-g_k\|_2
    >
    \frac{\sigma_{g,k}}
         {\sqrt{\delta\,\mathrm{ESS}_k}}
    \,\middle|\,
    \mathcal F_{k-1}
  \right)
  \le\delta ,
\]
which proves the high-probability statement.

\subsection{Proof of Theorem~\ref{thm:current-ess}}

Let $\varepsilon_k=\varepsilon_k(\delta)$ and consider the event
$\|\widehat g_k-g_k\|_2\le\varepsilon_k$, which has conditional probability at
least $1-\delta$ by Lemma~\ref{lem:ess-gradient-reliability}.  Smoothness gives,
for any $\alpha\ge0$,
\begin{align}
  J(\theta_k+\alpha\widehat g_k)-J(\theta_k)
  &\ge
  \alpha\langle g_k,\widehat g_k\rangle
  -\frac{L_k\alpha^2}{2}\|\widehat g_k\|_2^2\\
  &\ge
  \alpha\|\widehat g_k\|_2
  \{\|\widehat g_k\|_2-\varepsilon_k\}
  -\frac{L_k\alpha^2}{2}\|\widehat g_k\|_2^2 .
  \label{eq:smoothness-with-error}
\end{align}
The second line follows from Cauchy--Schwarz:
$\langle g_k,\widehat g_k\rangle
=\|\widehat g_k\|_2^2+
\langle g_k-\widehat g_k,\widehat g_k\rangle
\ge\|\widehat g_k\|_2
(\|\widehat g_k\|_2-\varepsilon_k)$.
The right-hand side of Equation~\eqref{eq:smoothness-with-error} is a concave
quadratic in $\alpha$.  Its nonnegative maximizer is
$\alpha_k=L_k^{-1}(1-\varepsilon_k/\|\widehat g_k\|_2)_+$, with the stated
zero convention.  Substitution gives
Equation~\eqref{eq:ess-policy-improvement}.

\subsection{Intact prompt groups}

Suppose $m$ prompts are independent and each prompt has $G$ conditionally
independent responses.  Keep every prompt group intact and define its gradient
contribution by
$\Xi_{k,i}:=G^{-1}\sum_{g=1}^G W_{k,ig}H_{k,ig}$.  The minibatch estimator is
$m^{-1}\sum_i\Xi_{k,i}$.  A leave-one-out baseline is admissible because, for a
focal response, it is measurable with respect to the prompt and the other
responses and is conditionally independent of the focal score.  Jensen's
inequality gives
\[
  \|\Xi_{k,i}\|_2^2
  \le
  \frac1G\sum_{g=1}^G
  W_{k,ig}^2\|H_{k,ig}\|_2^2 .
\]
Therefore the proof of Lemma~\ref{lem:ess-gradient-reliability} applies with
$m$ independent units and the corresponding member-level weighted moment.  The
resulting bound is conservative because it counts independent prompts rather
than all responses as independent observations.

\subsection{Bias--variance identity used in the diagnostics}

Let $X_W$ be an unbiased per-unit contribution with mean $g$, and let $X_C$ be
an alternative contribution.  Write $b_C:=\mathbb E[X_C]-g$ and let
$\Sigma_W$ and $\Sigma_C$ be the corresponding covariance matrices.  For
averages of $N$ independent units,
\begin{equation}
  \operatorname{MSE}(\widehat g_C)
  <\operatorname{MSE}(\widehat g_W)
  \quad\Longleftrightarrow\quad
  \operatorname{tr}(\Sigma_W)-\operatorname{tr}(\Sigma_C)
  >
  N\|b_C\|_2^2 .
  \label{eq:crossover}
\end{equation}
Indeed,
$\operatorname{MSE}(\widehat g_W)=N^{-1}\operatorname{tr}(\Sigma_W)$ and
$\operatorname{MSE}(\widehat g_C)=\|b_C\|_2^2+
N^{-1}\operatorname{tr}(\Sigma_C)$."""

