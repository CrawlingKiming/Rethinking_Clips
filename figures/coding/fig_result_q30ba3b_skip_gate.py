#!/usr/bin/env python
"""Unclipped-update skip ablation for Section 6.

The main plot isolates one intervention: keep the unclipped update throughout
training or skip it on a low-ESS minibatch. The TIS-5 pair is generated by
fig_result_q30ba3b_tis5.py as a separate Figure-5-style comparison.

Output:
  figures_mains/result/q30ba3b/skip_gate/overall.pdf
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import paperstyle
from paperstyle import COL, C, format_sig, use_paper_style, save
from runlog import series

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
paperstyle.FIGDIR = os.path.join(ROOT, "figures_mains")

VARIANTS = [
    ("noclip_ungated", "Unclipped", "#4d4d4d", "--", 1.2, -7),
    ("noclip_ess_skip", "ESS-conditioned", C["ours"], "-", 1.6, 7),
]


def annotate_endpoint(ax, x, y, color, offset):
    ax.annotate(
        f"{format_sig(y)}%",
        xy=(x, y), xytext=(5, offset), textcoords="offset points",
        color=color, fontsize=6.5, ha="left", va="center", clip_on=False,
    )


use_paper_style()
fig, axis = plt.subplots(figsize=(COL, 2.48))
for run, _label, color, linestyle, linewidth, offset in VARIANTS:
    xs, ys = series(run, "eval")
    values = [100 * value for value in ys]
    axis.plot(
        xs, values, color=color, linestyle=linestyle, linewidth=linewidth,
        marker="o", markersize=2.7,
    )
    annotate_endpoint(axis, xs[-1], values[-1], color, offset)

axis.set_xlim(-3, 203)
axis.set_ylim(-1.5, 50)
axis.set_xlabel("training step")
axis.set_ylabel("AIME-2024 mean@16 (%)")
axis.set_title("Unclipped update", loc="left", fontweight="bold")

handles = [
    Line2D([0], [0], color=color, linestyle=linestyle, linewidth=linewidth,
           marker="o", markersize=2.7, label=label)
    for _run, label, color, linestyle, linewidth, _offset in VARIANTS
]
fig.legend(
    handles=handles, loc="outside lower center", ncol=2, frameon=False,
    fontsize=8.0, handlelength=2.2,
)
save(fig, "result/q30ba3b/skip_gate/overall")
